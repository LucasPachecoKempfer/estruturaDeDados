    private int linhaInicial = 4;
    private int colunaInicial = 0;
    private int linhaFinal = 21;
    private int colunaFinal = 49;

    private final int totalColunas = mapa[0].length;

    private boolean[][] visitado;

    private Pilha<Integer> pilha = new Pilha<>(mapa.length * mapa[0].length);

    public void imprimir() {
        for (int i = 0; i < mapa.length; i++) {
            for (int j = 0; j < mapa[i].length; j++) {
                System.out.print(mapa[i][j]);
            }
            System.out.println();
        }
    }

    public int codificar(int linha, int coluna) {
        return linha * totalColunas + coluna;
    }

    public int linhaDe(int codigo) {
        return codigo / totalColunas;
    }

    public int colunaDe(int codigo) {
        return codigo % totalColunas;
    }


    public boolean resolver() {
        visitado = new boolean[mapa.length][mapa[0].length];

        int inicio = codificar(linhaInicial, colunaInicial);
        pilha.push(inicio);
        visitado[linhaInicial][colunaInicial] = true;

        while (!pilha.isEmpty()) {
            int atual = pilha.pop();

            int linha = linhaDe(atual);
            int coluna = colunaDe(atual);

            if (mapa[linha][coluna] == 'T') {
                pilha.push(atual);
                marcarCaminhoEncontrado();
                return true;
            }

            Integer proxima = proximaPosicaoLivre(linha, coluna);

            if (proxima != null) {

                pilha.push(atual);
                visitado[linhaDe(proxima)][colunaDe(proxima)] = true;
                pilha.push(proxima);
            }

        }

        return false;
    }

    public Integer proximaPosicaoLivre(int linha, int coluna) {
        int[][] direcoes = {
                {1, 0},   // baixo
                {0, 1},   // direita
                {-1, 0},  // cima
                {0, -1}   // esquerda
        };

        for (int[] direcao : direcoes) {
            int novaLinha = linha + direcao[0];
            int novaColuna = coluna + direcao[1];

            if (posicaoValida(novaLinha, novaColuna) && !visitado[novaLinha][novaColuna]) {
                char conteudo = mapa[novaLinha][novaColuna];
                if (conteudo == ' ' || conteudo == 'T') {
                    return codificar(novaLinha, novaColuna);
                }
            }
        }

        return null;
    }

    public boolean posicaoValida(int linha, int coluna) {
        return linha >= 0 && linha < mapa.length
                && coluna >= 0 && coluna < mapa[linha].length;
    }

    private void marcarCaminhoEncontrado() {
        while (!pilha.isEmpty()) {
            int codigo = pilha.pop();
            int linha = linhaDe(codigo);
            int coluna = colunaDe(codigo);
            if (mapa[linha][coluna] == ' ') {
                mapa[linha][coluna] = '+';
            }
        }
    }

